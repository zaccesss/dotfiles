#!/usr/bin/env python3
"""Writes every terminal's theme files from palette/zacess.json.

The palette holds the terminal colours of the eight Zacess themes from Zacess Themes 0.3.0, copied
from that project's own palette. Every terminal gets all eight, so any of them can be picked, and
Zacess Deep Contrast Dark is the default. No terminal follows the system light and dark setting:
the theme stays fixed until it is changed by hand or with the `zt` command in the dotfiles.
Every file this script writes is generated, so edit the palette and run the script again rather
than editing an output by hand. `--check` exits non-zero when a committed file is out of date or a
colour drops below its contrast floor, which CI runs.
"""

import json
import plistlib
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTE = json.loads((ROOT / "palette" / "zacess.json").read_text())
THEMES = PALETTE["themes"]
DEFAULT = next(t for t in THEMES if t["id"] == PALETTE["default"])
NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
PLATFORMS = ["mac", "linux", "windows"]
HEADER = "generated by scripts/build-themes.py from palette/zacess.json, do not edit by hand"


def iterm_guid(theme):
    # the default theme keeps the Guid the earlier High Contrast profile had, so iTerm2's default
    # profile setting still points at it; every other theme gets its own fixed Guid, so
    # regenerating never adds a second copy of a profile
    if theme["id"] == PALETTE["default"]:
        return str(uuid.uuid5(uuid.NAMESPACE_URL, "terminal-config/high-contrast"))
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"terminal-config/zacess-{theme['id']}"))


def rgb(hex_colour):
    return [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]


def slug(theme):
    return f"zacess-{theme['id']}"


def colours16(theme):
    return theme["ansi"] + theme["bright"]


def alacritty(t):
    lines = [f"# {t['name']}", f"# {HEADER}", "", "[colors.primary]", f'background = "{t["background"]}"',
             f'foreground = "{t["foreground"]}"', "", "[colors.cursor]", f'cursor = "{t["cursor"]}"',
             f'text = "{t["background"]}"', "", "[colors.selection]",
             f'background = "{t["selection_background"]}"', f'text = "{t["selection_foreground"]}"']
    for kind in ("normal", "bright"):
        lines += ["", f"[colors.{kind}]"]
        values = t["ansi"] if kind == "normal" else t["bright"]
        lines += [f'{name} = "{value}"' for name, value in zip(NAMES, values)]
    return "\n".join(lines) + "\n"


def kitty(t):
    lines = [f"# {t['name']}", f"# {HEADER}", f"background {t['background']}", f"foreground {t['foreground']}",
             f"cursor {t['cursor']}", f"cursor_text_color {t['background']}",
             f"selection_background {t['selection_background']}",
             f"selection_foreground {t['selection_foreground']}"]
    lines += [f"color{i} {value}" for i, value in enumerate(colours16(t))]
    return "\n".join(lines) + "\n"


def warp(t):
    lines = [f"# {HEADER}", f"name: {t['name']}", f"accent: '{t['ansi'][4]}'",
             f"background: '{t['background']}'", f"foreground: '{t['foreground']}'",
             f"details: {'darker' if t['appearance'] == 'dark' else 'lighter'}", "terminal_colors:"]
    for kind, values in (("normal", t["ansi"]), ("bright", t["bright"])):
        lines.append(f"  {kind}:")
        lines += [f"    {name}: '{value}'" for name, value in zip(NAMES, values)]
    return "\n".join(lines) + "\n"


HYPER_START = "    // palette start, generated by scripts/build-themes.py from palette/zacess.json\n"
HYPER_END = "    // palette end\n"
HYPER_OLD_START = "    // palette start, generated by scripts/build-themes.py from palette/high-contrast.json\n"


def hyper(current):
    # Hyper has no theme files of its own, so it carries the default theme only. Only the block
    # between the palette markers is rewritten, so each platform keeps its own font
    t = DEFAULT
    current = current.replace(HYPER_OLD_START, HYPER_START)
    colours = "".join(
        [f'      {name}: "{value}",\n' for name, value in zip(NAMES, t["ansi"])]
        + [f'      light{name.capitalize()}: "{value}",\n' for name, value in zip(NAMES, t["bright"])])
    block = (HYPER_START
             + f'    backgroundColor: "{t["background"]}",\n'
             + f'    foregroundColor: "{t["foreground"]}",\n'
             + f'    cursorColor: "{t["cursor"]}",\n'
             + f'    selectionColor: "{t["selection_background"]}",\n'
             + "    colors: {\n" + colours + "    },\n"
             + HYPER_END)
    if HYPER_START not in current or HYPER_END not in current:
        raise SystemExit("hyper.js is missing the palette start and end markers")
    before = current[:current.index(HYPER_START)]
    after = current[current.index(HYPER_END) + len(HYPER_END):]
    return before + block + after


def iterm_colour(hex_colour):
    r, g, b = rgb(hex_colour)
    return {"Red Component": r, "Green Component": g, "Blue Component": b,
            "Alpha Component": 1, "Color Space": "sRGB"}


def iterm():
    profiles = []
    for t in THEMES:
        profile = {
            "Name": t["name"],
            "Guid": iterm_guid(t),
            # the font is set here because iTerm2's own Default profile starts on Monaco, which has
            # none of the Nerd Font icons the prompt draws outside Terminal.app. Everything else
            # (bell, scrollback) is still inherited from the profile named Default
            "Dynamic Profile Parent Name": "Default",
            "Normal Font": "GeistMonoNFM 12",
            "Non Ascii Font": "GeistMonoNFM 12",
            "Use Separate Colors for Light and Dark Mode": False,
            "Use Bright Bold": False,
        }
        for key, value in (("Background Color", t["background"]), ("Foreground Color", t["foreground"]),
                           ("Bold Color", t["foreground"]), ("Cursor Color", t["cursor"]),
                           ("Cursor Text Color", t["background"]),
                           ("Selection Color", t["selection_background"]),
                           ("Selected Text Color", t["selection_foreground"])):
            profile[key] = iterm_colour(value)
        for i, value in enumerate(colours16(t)):
            profile[f"Ansi {i} Color"] = iterm_colour(value)
        profiles.append(profile)
    return json.dumps({"Profiles": profiles}, indent=2) + "\n"


def ns_archive(root_object, class_name, extra_classes):
    return plistlib.dumps({
        "$archiver": "NSKeyedArchiver",
        "$version": 100000,
        "$top": {"root": plistlib.UID(1)},
        "$objects": ["$null", root_object] + extra_classes
        + [{"$classname": class_name, "$classes": [class_name, "NSObject"]}],
    }, fmt=plistlib.FMT_BINARY)


def ns_colour(hex_colour):
    # NSSpaceID 12 is sRGB, so Terminal.app shows exactly the palette's values. The device RGB form
    # its older built-in profiles use is converted to the display's own space and comes out darker
    components = (" ".join(f"{c:.10g}" for c in rgb(hex_colour)) + " 1").encode()
    return plistlib.dumps({
        "$archiver": "NSKeyedArchiver",
        "$version": 100000,
        "$top": {"root": plistlib.UID(1)},
        "$objects": [
            "$null",
            {"NSColorSpace": 1, "NSComponents": components, "NSRGB": components + b"\x00",
             "NSCustomColorSpace": plistlib.UID(2), "$class": plistlib.UID(4)},
            {"NSSpaceID": 12, "$class": plistlib.UID(3)},
            {"$classname": "NSColorSpace", "$classes": ["NSColorSpace", "NSObject"]},
            {"$classname": "NSColor", "$classes": ["NSColor", "NSObject"]},
        ],
    }, fmt=plistlib.FMT_BINARY)


def ns_font(name, size):
    obj = {"NSName": plistlib.UID(2), "NSSize": float(size), "NSfFlags": 16, "$class": plistlib.UID(3)}
    return ns_archive(obj, "NSFont", [name])


TERMINAL_APP_KEYS = ["ANSIBlackColor", "ANSIRedColor", "ANSIGreenColor", "ANSIYellowColor",
                     "ANSIBlueColor", "ANSIMagentaColor", "ANSICyanColor", "ANSIWhiteColor",
                     "ANSIBrightBlackColor", "ANSIBrightRedColor", "ANSIBrightGreenColor",
                     "ANSIBrightYellowColor", "ANSIBrightBlueColor", "ANSIBrightMagentaColor",
                     "ANSIBrightCyanColor", "ANSIBrightWhiteColor"]


def terminal_app(t):
    profile = {
        "name": t["name"],
        "type": "Window Settings",
        "ProfileCurrentVersion": 2.09,
        "BackgroundColor": ns_colour(t["background"]),
        "TextColor": ns_colour(t["foreground"]),
        "TextBoldColor": ns_colour(t["foreground"]),
        "CursorColor": ns_colour(t["cursor"]),
        "SelectionColor": ns_colour(t["selection_background"]),
        "Font": ns_font("SFMonoTerminal-Regular", 12),
        "FontAntialias": True,
        # bold keeps the normal colour rather than switching to the bright row
        "UseBrightBold": False,
        "columnCount": 120,
        "rowCount": 32,
    }
    for key, value in zip(TERMINAL_APP_KEYS, colours16(t)):
        profile[key] = ns_colour(value)
    return plistlib.dumps(profile, fmt=plistlib.FMT_XML, sort_keys=True)


def windows_terminal():
    keys = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white"]
    schemes = []
    for t in THEMES:
        scheme = {"name": t["name"], "background": t["background"], "foreground": t["foreground"],
                  "cursorColor": t["cursor"], "selectionBackground": t["selection_background"]}
        scheme.update(dict(zip(keys, t["ansi"])))
        scheme.update({"bright" + k.capitalize(): v for k, v in zip(keys, t["bright"])})
        schemes.append(scheme)
    return json.dumps({"$help": HEADER, "schemes": schemes}, indent=2) + "\n"


def ptyxis(t):
    # Ptyxis palettes carry a light and a dark half; both get the same colours, so the theme stays
    # fixed whatever the system appearance
    lines = [f"# {HEADER}", "[Palette]", f"Name={t['name']}"]
    for mode in ("Light", "Dark"):
        lines += ["", f"[{mode}]", f"Foreground={t['foreground']}",
                  f"Background={t['background']}", f"Cursor={t['cursor']}"]
        lines += [f"Color{i}={value}" for i, value in enumerate(colours16(t))]
    return "\n".join(lines) + "\n"


def gnome_terminal(t):
    palette = ", ".join(f"'{c}'" for c in colours16(t))
    return f"""# {t['name']}
# {HEADER}
# load with: dconf load /org/gnome/terminal/legacy/profiles:/:<profile id>/ < {slug(t)}.dconf
[/]
visible-name='{t['name']}'
use-theme-colors=false
background-color='{t['background']}'
foreground-color='{t['foreground']}'
bold-is-bright=false
cursor-colors-set=true
cursor-background-color='{t['cursor']}'
cursor-foreground-color='{t['background']}'
highlight-colors-set=true
highlight-background-color='{t['selection_background']}'
highlight-foreground-color='{t['selection_foreground']}'
palette=[{palette}]
"""


TABLE_START = "<!-- palette table start: generated by scripts/build-themes.py -->\n"
TABLE_END = "<!-- palette table end -->\n"


def palette_table(current):
    # the guide's colour tables are generated too, so the documented values can never drift
    out = []
    for t in THEMES:
        out += [f"### {t['name']}", "",
                f"Short name `{t['short']}`, {t['appearance']}. Text `{t['foreground']}` on `{t['background']}` "
                f"({contrast(t['foreground'], t['background']):.1f}:1).", "",
                "| Colour | Normal | Bright |", "| --- | --- | --- |"]
        for name, normal, bright in zip(NAMES, t["ansi"], t["bright"]):
            out.append(f"| {name} | `{normal}` ({contrast(normal, t['background']):.1f}:1) | "
                       f"`{bright}` ({contrast(bright, t['background']):.1f}:1) |")
        out.append("")
    block = TABLE_START + "\n".join(out) + TABLE_END
    if TABLE_START not in current or TABLE_END not in current:
        raise SystemExit("the guide is missing the palette table markers")
    return current[:current.index(TABLE_START)] + block + current[current.index(TABLE_END) + len(TABLE_END):]


def outputs():
    # a terminal's files are written only where the repo already has that terminal's folder, so the
    # same script serves a repo that covers fewer terminals
    files = {}
    for platform in PLATFORMS:
        base = ROOT / platform
        for t in THEMES:
            if (base / "alacritty").is_dir():
                files[f"{platform}/alacritty/{slug(t)}.toml"] = alacritty(t)
            if (base / "kitty").is_dir():
                files[f"{platform}/kitty/{slug(t)}.conf"] = kitty(t)
            if (base / "warp").is_dir():
                files[f"{platform}/warp/themes/{slug(t)}.yaml"] = warp(t)
        hyper_file = base / "hyper" / "hyper.js"
        if hyper_file.exists():
            files[f"{platform}/hyper/hyper.js"] = hyper(hyper_file.read_text())
    files["mac/iterm2/zacess.json"] = iterm()
    for t in THEMES:
        files[f"mac/terminal-app/{t['name']}.terminal"] = terminal_app(t)
        files[f"linux/ptyxis/{slug(t)}.palette"] = ptyxis(t)
        files[f"linux/gnome-terminal/{slug(t)}.dconf"] = gnome_terminal(t)
    files["windows/windows-terminal/zacess.json"] = windows_terminal()
    guide = ROOT / "guides" / "themes.md"
    if guide.exists():
        files["guides/themes.md"] = palette_table(guide.read_text())
    return files


def luminance(hex_colour):
    channels = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb(hex_colour)]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a, b):
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def low_contrast():
    # the same floors Zacess Themes holds itself to: text 7:1 (WCAG AAA) on the background, every
    # terminal colour 7:1 apart from the slots a theme marks as dim (held to 4.5:1, the terminal
    # allowance that keeps light themes vivid) and the slots it marks as background shades
    problems = []
    for t in THEMES:
        checks = [("foreground", t["foreground"], t["background"], 7),
                  ("selection", t["selection_foreground"], t["selection_background"], 7)]
        for i, value in enumerate(colours16(t)):
            if i in t["background_role"]:
                continue
            checks.append((f"color{i}", value, t["background"], 4.5 if i in t["dim"] else 7))
        # the palette's values are whole hex steps, so a ratio a hair under the floor still counts
        problems += [f"{t['name']} {name} {ratio:.2f}:1" for name, fg, bg, floor in checks
                     if (ratio := contrast(fg, bg)) < floor - 0.05]
    return problems


def main():
    check = "--check" in sys.argv[1:]
    problems = low_contrast()
    if problems:
        print("below the contrast floor:\n  " + "\n  ".join(problems))
        sys.exit(1)
    stale = []
    for relative, content in outputs().items():
        path = ROOT / relative
        data = content if isinstance(content, bytes) else content.encode()
        if path.exists() and path.read_bytes() == data:
            continue
        if check:
            stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f"wrote {relative}")
    if stale:
        print("out of date, run scripts/build-themes.py:\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
