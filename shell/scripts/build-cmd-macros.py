#!/usr/bin/env python3
"""Writes windows/cmd/macros.doskey from the one-line functions in windows/topics/*.ps1.

Command Prompt has no functions, only doskey macros: one line of text with $1 to $9 and $* standing
for the arguments and $T between commands. A PowerShell function becomes a macro when its body is a
plain command line: an external program with its arguments, $args or @args passed through, simple
param() names used as positional arguments, Set-Location, Start-Process on a web address or several
of those joined with ;. Anything else needs PowerShell itself (pipelines of objects, cmdlets,
variables, script blocks or a call to another PowerShell function), so it is listed in
windows/cmd/README.md with the reason instead. Run it again after changing a topic file;
`--check` exits non-zero when the committed files are out of date.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOPICS = ROOT / "windows" / "topics"
MACROS = ROOT / "windows" / "cmd" / "macros.doskey"
README = ROOT / "windows" / "cmd" / "README.md"
START = "<!-- not ported start: generated by scripts/build-cmd-macros.py -->\n"
END = "<!-- not ported end -->\n"

FUNCTION = re.compile(r"^function ([A-Za-z0-9_-]+)\s*\{\s*(.*?)\s*\}\s*(?:#.*)?$")
PARAMS = re.compile(r"^param\(\s*((?:\[[\w\[\]]+\]\s*)?\$\w+(?:\s*,\s*(?:\[[\w\[\]]+\]\s*)?\$\w+)*)\s*\)\s*(.+)$")
# PowerShell aliases that are not the Command Prompt command of the same name, so a line starting
# with one only works in PowerShell
# Command Prompt's own commands, which a macro of the same name would hide
CMD_BUILTINS = {"assoc", "break", "call", "cd", "chdir", "cls", "color", "copy", "date", "del", "dir", "echo",
                "endlocal", "erase", "exit", "for", "ftype", "goto", "if", "md", "mkdir", "mklink", "move",
                "path", "pause", "popd", "prompt", "pushd", "rd", "rem", "ren", "rename", "rmdir", "set",
                "setlocal", "shift", "start", "time", "title", "type", "ver", "verify", "vol"}
PS_ONLY = {"ls", "cat", "cp", "mv", "rm", "man", "ps", "kill", "sleep", "sort", "tee", "where", "select",
           "gci", "gc", "sl", "iwr", "irm", "curl", "wget", "write", "measure", "foreach", "%", "?"}


def split_commands(body):
    # ; separates commands only outside quotes
    parts, current, quote = [], "", None
    for c in body:
        if quote:
            quote = None if c == quote else quote
        elif c in "\"'":
            quote = c
        elif c == ";":
            parts.append(current.strip())
            current = ""
            continue
        current += c
    parts.append(current.strip())
    return parts


def convert(name, body, functions):
    """returns (macro text, None) or (None, reason)"""
    if name.lower() in CMD_BUILTINS:
        return None, f"would hide Command Prompt's own `{name}`"
    if re.search(r"\s-(?:split|join|replace|match|like|eq|ne|f)\b", body):
        return None, "uses a PowerShell operator"
    names = []
    m = PARAMS.match(body)
    if m:
        names = [re.sub(r"^\[[\w\[\]]+\]\s*", "", p.strip())[1:] for p in m.group(1).split(",")]
        if len(names) > 9:
            return None, "takes more than nine named arguments"
        body = m.group(2)
    elif body.startswith("param("):
        return None, "has typed, default or validated parameters"
    parts = split_commands(body)
    out = []
    for part in parts:
        if not part:
            continue
        words = part.split()
        first = words[0]
        if first == "Set-Location" and len(words) == 2:
            path = words[1].replace("$HOME", "%USERPROFILE%")
            if "$" in path:
                return None, "changes to a folder held in a PowerShell variable"
            out.append(f'cd /d "{path.strip(chr(34))}"')
            continue
        if first == "Start-Process" and len(words) == 2 and re.match(r'^"https?://[^"$]*"$', words[1]):
            out.append(f'start "" {words[1]}')
            continue
        if re.search(r"[|{}()`&]|\b(?:Get|Set|New|Remove|Write|Invoke|Start|Test|Select|Out|Copy|Move|Join|Push|Pop|"
                     r"ConvertTo|ConvertFrom|Format|Where|ForEach|Measure|Sort|Import|Export|Read|Add)-", part):
            return None, "uses PowerShell syntax or a cmdlet"
        if first.lower().endswith(".ps1"):
            return None, "runs a PowerShell script"
        if first in functions:
            return None, f"calls the PowerShell function `{first}`"
        if first.lower() in PS_ONLY:
            return None, f"`{first}` is a PowerShell alias there, not the Command Prompt command"
        if "%" in part:
            return None, "contains % signs, which Command Prompt reads as variables"
        # Command Prompt only knows double quotes, so a single-quoted PowerShell string becomes one
        text = re.sub(r"'([^'\"]*)'", r'"\1"', part)
        for i, param in enumerate(names, 1):
            text = re.sub(r"\$" + param + r"\b", f"${i}", text)
        text = text.replace("@args", "$*").replace("$args", "$*")
        text = re.sub(r"\$env:(\w+)", r"%\1%", text).replace("$HOME", "%USERPROFILE%")
        if re.search(r"\$(?![1-9*])", text):
            return None, "uses a PowerShell variable"
        out.append(text.replace("<", "$L").replace(">", "$G"))
    if not out:
        return None, "has an empty body"
    return " $T ".join(out), None


def build():
    functions = {}
    macros, skipped = [], []
    for path in sorted(TOPICS.glob("*.ps1")):
        for line in path.read_text().splitlines():
            m = re.match(r"^function ([A-Za-z0-9_-]+)", line)
            if m:
                functions[m.group(1)] = path.name
    for path in sorted(TOPICS.glob("*.ps1")):
        for line in path.read_text().splitlines():
            if line.startswith("function ") and not FUNCTION.match(line):
                name = re.match(r"^function ([A-Za-z0-9_-]+)", line)
                if name:
                    skipped.append((path.name, name.group(1), "spans several lines of PowerShell"))
                continue
            m = FUNCTION.match(line)
            if not m:
                continue
            name, body = m.group(1), m.group(2)
            if name.startswith("_"):
                continue
            text, reason = convert(name, body, functions)
            if text:
                macros.append((path.name, name, text))
            else:
                skipped.append((path.name, name, reason))
    # doskey has no comment syntax, so each note is a macro named ";", the usual way to comment a macro file
    lines = [";= generated by scripts/build-cmd-macros.py from windows/topics/*.ps1, do not edit by hand",
             ";= loaded by autorun.cmd with doskey /macrofile"]
    current = None
    for topic, name, text in macros:
        if topic != current:
            lines.append(f";= {topic}")
            current = topic
        lines.append(f"{name}={text}")
    macro_file = "\r\n".join(lines) + "\r\n"
    rows = ["| Topic | Function | Why it stays in PowerShell |", "| --- | --- | --- |"]
    rows += [f"| `{t}` | `{n}` | {r} |" for t, n, r in skipped]
    table = (f"{len(macros)} functions are macros in Command Prompt. These {len(skipped)} are not:\n\n"
             + "\n".join(rows) + "\n")
    readme = README.read_text()
    if START not in readme or END not in readme:
        raise SystemExit("windows/cmd/README.md is missing the not ported markers")
    readme = readme[:readme.index(START)] + START + table + readme[readme.index(END):]
    return {MACROS: macro_file.encode(), README: readme.encode()}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, data in build().items():
        if path.exists() and path.read_bytes() == data:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date, run scripts/build-cmd-macros.py:\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
